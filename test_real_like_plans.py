EXPECTED_REFUSALS = {
    'C40': '#N/A',
}


def plan_tuple(plan):
    if plan is None:
        return None
    return tuple(plan.get(k) or '' for k in ('action', 'key', 'value', 'ref_key', 'ref_value'))


def snapshot_key(source, reference):
    return (source, reference)


def load_snapshots():
    cache = {}
    errors = []
    for name, filename in FILES.items():
        path = DATA / filename
        try:
            snap = app.inspect_file(
                str(path), header_row='auto',
                lenient=(name == 'so_quy'),
            )
            cache[name] = snap
        except Exception as exc:  # pragma: no cover - reported, not hidden
            errors.append({'file': filename, 'error': f'{type(exc).__name__}: {exc}'})
    return cache, errors


def execute_case(case, snapshots, tmpdir):
    source = snapshots[case[1]]
    reference = snapshots.get(case[2]) if case[2] else None
    plan = ai_client.infer_smart_plan(case[3], source['headers'],
                                      reference['headers'] if reference else ())
    preview = app.preview_plan(source, reference, plan, output_dir=tmpdir)
    report = app.execute(source, reference, plan, output_dir=tmpdir,
                         approval_token=preview['approval_token'])
    output = Path(report['output'])
    if not output.exists() or not output.is_file():
        raise RuntimeError('output file was not published')
    return {
        'output': output.name,
        'formula_checks': report.get('formula_checks'),
        'saved_cell_checks': report.get('saved_cell_checks'),
        'preserved': (report.get('preservation') or {}).get('unchanged'),
    }


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument('--no-execute', action='store_true',
                        help='measure planning only; skip the Excel write path')
    args = parser.parse_args(argv)

    snapshots, read_errors = load_snapshots()
    for error in read_errors:
        print(f"[READ FAIL] {error['file']}: {error['error']}")
    if read_errors:
        print(f'FAIL: could not inspect {len(read_errors)}/{len(FILES)} workbooks')
        return 1

    rows = []
    for case in CURATED + KNOWN_LIMITATIONS:
        case_id, source_name, ref_name, prompt, expected = case[:5]
        limitation = len(case) > 5 and case[5] or None
        source = snapshots[source_name]
        reference = snapshots.get(ref_name) if ref_name else None
        actual = ai_client.infer_smart_plan(
            prompt, source['headers'],
            reference['headers'] if reference else (),
        )
        got = plan_tuple(actual)
        correct = got == expected
        rows.append({
            'id': case_id,
            'kind': 'known_limitation' if limitation else 'curated',
            'source': FILES[source_name],
            'reference': FILES.get(ref_name) if ref_name else None,
            'prompt': prompt,
            'expected': expected,
            'actual': got,
            'plan_matches': correct,
            'fix_note': limitation,
        })
        mark = 'PASS' if correct else 'MISS'
        print(f'[{mark}] {case_id} {prompt}')
        if not correct:
            print(f'        expected={expected}')
            print(f'        actual  ={got}')

    curated = [row for row in rows if row['kind'] == 'curated']
    limitations = [row for row in rows if row['kind'] == 'known_limitation']
    curated_ok = sum(1 for row in curated if row['plan_matches'])
    limits_ok = sum(1 for row in limitations if row['plan_matches'])
    accuracy = (curated_ok + limits_ok) / len(rows)

    execution = {'requested': not args.no_execute, 'passed': 0,
                 'refused_as_expected': 0, 'failed': 0, 'cases': []}
    if not args.no_execute:
        # Run the full preview -> approval -> Excel write -> verify path for
        # every curated prompt whose plan is exactly the intended one.  Cases
        # that are knowingly misplanned are never executed.
        correct_ids = {row['id'] for row in curated if row['plan_matches']}
        with tempfile.TemporaryDirectory(prefix='q4-exec-', dir=app.WORK) as tmp:
            for case in CURATED:
                if case[0] not in correct_ids:
                    continue
                started = time.perf_counter()
                try:
                    info = execute_case(case, snapshots, tmp)
                    execution['passed'] += 1
                    execution['cases'].append({
                        'id': case[0], 'ok': True,
                        'seconds': round(time.perf_counter() - started, 3), **info,
                    })
                    print(f'[EXEC] {case[0]} ok ({execution["cases"][-1]["seconds"]}s)')
                except Exception as exc:  # pragma: no cover - reported, not hidden
                    expected_refusal = EXPECTED_REFUSALS.get(case[0])
                    message = f'{type(exc).__name__}: {exc}'
                    if expected_refusal and expected_refusal in message:
                        execution['refused_as_expected'] += 1
                        execution['cases'].append({
                            'id': case[0], 'ok': True, 'refused': True,
                            'expected_refusal': expected_refusal,
                            'error': message,
                        })
                        print(f'[EXEC REFUSED AS EXPECTED] {case[0]}: {message}')
                    else:
                        execution['failed'] += 1
                        execution['cases'].append({
                            'id': case[0], 'ok': False,
                            'error': message,
                        })
                        print(f'[EXEC FAIL] {case[0]}: {message}')

    payload = {
        'generated_at': time.strftime('%Y-%m-%d %H:%M:%S'),
        'workbooks': len(FILES),
        'prompts': len(rows),
        'curated': len(curated),
        'known_limitations': len(limitations),
        'curated_correct': curated_ok,
        'known_limitations_correct': limits_ok,
        'first_plan_accuracy': round(accuracy, 4),
        'accuracy_note': 'Correct plans / all 55 prompts, counted before repair.',
        'execution': execution,
        'cases': rows,
    }
    RESULTS.parent.mkdir(parents=True, exist_ok=True)
    RESULTS.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding='utf-8')

    print()
    print(f'Workbooks inspected: {len(FILES)}/{len(FILES)}')
    print(f'Curated plans correct: {curated_ok}/{len(curated)}')
    print(f'Known limitations still wrong: {len(limitations) - limits_ok}/{len(limitations)}')
    print(f'Measured first-plan accuracy: {accuracy:.1%} ({curated_ok + limits_ok}/{len(rows)})')
    if execution['requested']:
        print(f'End-to-end executions: {execution["passed"]} passed, '
              f'{execution["refused_as_expected"]} refused as expected, '
              f'{execution["failed"]} failed')
    print(f'Saved: {RESULTS.relative_to(ROOT)}')

    if execution['failed']:
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
